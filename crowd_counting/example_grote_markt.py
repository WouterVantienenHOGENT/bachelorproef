"""Reproduce the thesis example using the four trained CSRNet runs."""

import csv
import hashlib
import json
from pathlib import Path

import torch
from PIL import Image

from infer import InferenceOptions, predict_image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "graphics/voorbeelden/grote-markt-sint-niklaas"
RESULTS = ROOT / "bachproef/voorbeelden/grote-markt-sint-niklaas"
RUNS = [
    ("CPU-kalibratie", "shanghaitech_part_b_cpu_first"),
    ("GPU-kalibratie", "shanghaitech_part_b_gpu_calibration_512_b4"),
    ("Gecontroleerde run, 1 epoch", "shanghaitech_part_b_gpu_512_b4_e1_seed42_finalcode"),
    ("Finale run, 100 epochs", "shanghaitech_part_b_gpu_512_b4_e100_seed42"),
]


def main():
    RESULTS.mkdir(parents=True, exist_ok=True)
    source = ASSETS / "origineel.png"
    with Image.open(source) as image:
        original_size = image.size
        image = image.convert("RGB")
        size = (1024, round(image.height * 1024 / image.width))
        image.resize(size, Image.Resampling.LANCZOS).save(ASSETS / "invoer.png")

    rows = []
    for label, run in RUNS:
        checkpoint = ROOT / "bachproef/runs" / run / "best.pt"
        summary = json.loads(checkpoint.with_name("summary.json").read_text())
        result = predict_image(InferenceOptions(
            checkpoint=str(checkpoint), image=str(ASSETS / "invoer.png"),
            output_dir=str(RESULTS / run), device="cuda",
            warmup_runs=3, timed_runs=20, benchmark_csv="",
        ))
        with checkpoint.open("rb") as stream:
            checkpoint_hash = hashlib.file_digest(stream, "sha256").hexdigest()
        result.update(
            label=label, run=run, validation_mae=summary["best_val_mae"],
            checkpoint_sha256=checkpoint_hash,
        )
        rows.append(result)
        print(label, result["estimated_count"], result["mean_forward_ms"], flush=True)

    best = min(rows, key=lambda row: row["validation_mae"])
    (ASSETS / "beste-heatmap.png").write_bytes(
        (RESULTS / best["run"] / "invoer_density.png").read_bytes()
    )
    metadata = {
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "original_size": original_size, "input_size": size,
        "resize": "Pillow LANCZOS, aspect ratio preserved, width 1024",
        "torch_version": torch.__version__, "cuda_version": torch.version.cuda,
        "selection": "Lowest ShanghaiTech Part B validation MAE, not this image",
        "selected_run": best["run"], "results": rows,
    }
    (RESULTS / "comparison.json").write_text(json.dumps(metadata, indent=2) + "\n")
    fields = ["label", "run", "checkpoint_epoch", "validation_mae", "estimated_count", "mean_forward_ms"]
    with (RESULTS / "comparison.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)

    def number(value, decimals=1):
        return f"{value:.{decimals}f}".replace(".", "{,}")

    lines = ["% Generated by crowd_counting/example_grote_markt.py"]
    for row in rows:
        lines.append(
            f'{row["label"]} & {row["checkpoint_epoch"]} & '
            f'\\({number(row["estimated_count"])}\\) & '
            f'\\({number(row["mean_forward_ms"], 2)}\\) \\\\'
        )
    lines.append(r"\bottomrule")
    (RESULTS / "tabel.tex").write_text("\n".join(lines) + "\n")
    (RESULTS / "telling.tex").write_text(f'\\({number(best["estimated_count"])}\\)%\n')


if __name__ == "__main__":
    main()
