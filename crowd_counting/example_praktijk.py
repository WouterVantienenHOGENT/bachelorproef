"""Generate the two thesis photo comparisons with one inference protocol."""

import csv
import hashlib
import json
import shutil
from pathlib import Path

from PIL import Image

from infer import InferenceOptions, predict_image
from plot_praktijk import generate_figures


ROOT = Path(__file__).resolve().parents[1]
MODELS = [
    ("CSRNet, CPU-kalibratie", "csrnet/csrnet_cpu_kalibratie.pt"),
    ("CSRNet, GPU-kalibratie", "csrnet/csrnet_gpu_kalibratie.pt"),
    ("CSRNet, één epoch", "csrnet/csrnet_een_epoch.pt"),
    ("CSRNet, finale run", "csrnet/csrnet_finaal.pt"),
    ("P2PNet, ShanghaiTech A", "p2pnet/p2pnet_shanghaitech_a.pth"),
]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def number(value, decimals=1):
    return f"{value:.{decimals}f}".replace(".", "{,}")


def main():
    for scene in ("grote-markt-sint-niklaas", "trevifontein-rome"):
        assets = ROOT / "graphics/voorbeelden" / scene
        source = assets / "origineel.png"
        output = ROOT / "bachproef/voorbeelden/praktijk" / scene
        output.mkdir(parents=True, exist_ok=True)
        with Image.open(source) as image:
            original_size = image.size
            image = image.convert("RGB")
            scale = min(1, 1024 / max(image.size))
            image.resize(
                tuple(round(side * scale) for side in image.size),
                Image.Resampling.LANCZOS,
            ).save(assets / "foto.png")

        rows = []
        for label, model in MODELS:
            checkpoint = ROOT / "models" / model
            result = predict_image(InferenceOptions(
                checkpoint=str(checkpoint), image=str(source),
                output_dir=str(output / checkpoint.stem), device="cuda",
                max_edge=1024, threshold=0.5,
                warmup_runs=3, timed_runs=20, benchmark_csv="",
            ))
            result.update(label=label, checkpoint_sha256=digest(checkpoint))
            rows.append(result)
            if checkpoint.stem == "csrnet_finaal":
                shutil.copyfile(
                    output / checkpoint.stem / "origineel_density.png",
                    assets / "praktijk-heatmap.png",
                )
            print(scene, label, result["estimated_count"], flush=True)

        metadata = {
            "source_sha256": digest(source), "original_size": original_size,
            "heatmap_selection": "Final CSRNet checkpoint, selected by Part B validation MAE",
            "results": rows,
        }
        (output / "comparison.json").write_text(json.dumps(metadata, indent=2) + "\n")
        fields = ["label", "checkpoint_epoch", "image_size", "estimated_count", "mean_forward_ms"]
        with (output / "comparison.csv").open("w", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(rows)
        lines = ["% Generated by crowd_counting/example_praktijk.py"]
        for row in rows:
            width, height = row["image_size"]
            lines.append(
                f'{row["label"]} & \\({width} \\times {height}\\) & '
                f'\\({number(row["estimated_count"], 0 if row["architecture"] == "p2pnet" else 1)}\\) & '
                f'\\({number(row["mean_forward_ms"], 2)}\\) \\\\'
            )
        lines.append(r"\bottomrule")
        (output / "tabel.tex").write_text("\n".join(lines) + "\n")

    generate_figures()


if __name__ == "__main__":
    main()
